#bitwise AND operator
a=5 #in binary 5 is 101
b=3 #in binary 3 is 011
print(a&b) #output is 1 (001 in binary)

#bitwise OR operator
a=5 #in binary 5 is 101 
b=3 #in binary 3 is 011
print(a|b) #output is 7 (111 in binary)

#bitwise XOR operator
a=5 #in binary 5 is 101
b=3 #in binary 3 is 011
print(a^b) #output is 6 (110 in binary)

#bitwise NOT operator
a=5 #in binary 5 is 101
b=3 #in binary 3 is 011
print(~a) #output is -6 (in two's complement)
print(~b) #output is -4 (in two's complement)

#bitwise left shift operator
a=5 #in binary 5 is 101
b=3 #in binary 3 is 011
print(a<<1) #output is 10 (1010 in binary)
print(b<<1) #output is 6 (110 in binary)

#bitwise right shift operator
a=5 #in binary 5 is 101
b=3 #in binary 3 is 011
print(a>>1) #output is 2 (10 in binary)
print(b>>1) #output is 1 (1 in binary)